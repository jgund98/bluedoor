export function srcSetFor(src: string): string | undefined {
  const name = src.match(/\/images\/([a-z0-9-]+)\.jpg$/)?.[1];
  const w = name ? W[name] : undefined;
  if (!w) return undefined;
  if (w[0] >= w[1]) return undefined; // already small: one file is enough
  return src.replace("/images/", "/images/g/") + " " + w[0] + "w, " + src + " " + w[1] + "w";
}
